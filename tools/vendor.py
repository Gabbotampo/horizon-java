#!/usr/bin/env python3
"""Vendor the Java runtime into the native mod, which is one crate.

A Horizon native mod is one flat crate (docs/modding/src/how-to/native-mods/016-the-mods-crate.md):
the launcher stages a single crate and refuses path dependencies, so the bytecode runtime that
``mod/`` runs is copied into it instead of being linked. This tool is the one place that copy is
made, so the mod never drifts from ``crates/horizon-native-java``:

* it copies every ``.rs`` file of ``crates/horizon-native-java/src`` except ``main.rs`` (the
  command-line probe, which the mod does not use) into ``mod/src/runtime/``;
* each data file a vendored source embeds with ``include_str!("…")``/``include_bytes!("…")``
  (a generated table, a test oracle's JSON) is copied beside it byte for byte, so the vendored
  module still finds it. The path must be a string literal inside ``src``: anything else is an
  error, never a silently missing file;
* ``lib.rs`` becomes ``runtime/mod.rs``, the module the mod's ``src/lib.rs`` declares;
* each ``crate::`` path is rewritten to ``crate::runtime::``, because the runtime is no longer a
  crate root but a module of the mod's crate. Relative paths (``super::``, ``self::``) and the
  ``#[path]`` submodules of ``client_surface.rs`` need no change;
* ``mod/vendor.lock`` records the source commit and the SHA-256 of every vendored file and of the
  file it was made from. The vendored files are committed: a clean clone builds without running
  this tool.

The mod carries the runtime **commit** `mod/vendor.lock` records, not the runtime as it is on every
later commit, so there are two checks and they run in different places:

* ``--check-lock`` — the committed copy is what the lock says, i.e. nobody edited
  ``mod/src/runtime/`` by hand. Always applies (``tests/test_vendor_mod.py`` runs it, and so CI).
  A runtime-only change never fails it.
* ``--check`` — the committed copy also matches ``crates/horizon-native-java/src`` **as it is now**,
  i.e. the mod carries the runtime's current behaviour. A PR that changes ``mod/**`` or this tool
  must pass it, and CI runs it then (``.github/workflows/ci.yml``); a release of the mod refreshes
  the copy first. The runtime's own PRs are unaffected.

To refresh: run ``python3 tools/vendor.py`` in a mod PR (and before a mod release).

    python3 tools/vendor.py              # write (or refresh) mod/src/runtime and mod/vendor.lock
    python3 tools/vendor.py --check-lock # fail on a hand edit to the committed copy
    python3 tools/vendor.py --check      # also fail unless it matches the runtime source now
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

# The crate the runtime comes from, and the mod that carries a copy of it.
RUNTIME_SRC = Path("crates/horizon-native-java/src")
MOD = Path("mod")
VENDOR = MOD / "src" / "runtime"
LOCK = MOD / "vendor.lock"
# `main.rs` is the command-line probe: neither a module of the library nor anything the mod calls.
SKIP = {PurePosixPath("main.rs")}
# The crate-root path a vendored file's `crate::` becomes.
PREFIX = "crate::runtime::"
# The runtime keeps one item for every capability the probe, the corpus tools and the weaver use;
# a mod calls a handful. Its warnings are the crate's, not the mod's, so the vendored root module
# silences the two that the whole-crate copy necessarily raises.
ROOT_HEADER = "// @generated by tools/vendor.py from crates/horizon-native-java/src; do not edit.\n#![allow(dead_code, unused_imports)]\n\n"
LOCK_SCHEMA = 1
# `include_str!("path")` / `include_bytes!("path")`, with the literal path captured; and any use
# of the two macros at all, so one whose argument is not a plain literal is refused, not skipped.
INCLUDE_LITERAL = re.compile(rb'\binclude_(?:str|bytes)!\(\s*"([^"\\]+)"\s*\)')
INCLUDE_ANY = re.compile(rb"\binclude_(?:str|bytes)!\(")


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_commit(root: Path) -> str:
    """The commit of the tree the vendored files were copied from, or a marker outside git."""
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return out.stdout.strip()


def vendored_name(relative: PurePosixPath) -> PurePosixPath:
    """Where one source file goes in `mod/src/runtime/`."""
    return PurePosixPath("mod.rs") if relative == PurePosixPath("lib.rs") else relative


def included_files(src: Path, path: Path, original: bytes) -> list[PurePosixPath]:
    """The data files one source embeds, relative to `src`.

    `include_str!`/`include_bytes!` resolve their path against the including file's directory,
    which the vendored copy keeps, so each file is copied to the same relative place. A macro whose
    argument is not a plain string literal, or a path that leaves `src`, cannot be copied and stops
    the tool: the mod's build would otherwise fail on a file nobody vendored.
    """
    literal = INCLUDE_LITERAL.findall(original)
    if len(literal) != len(INCLUDE_ANY.findall(original)):
        raise SystemExit(f"{path}: include_str!/include_bytes! of a non-literal path cannot be vendored")
    out = []
    for raw in literal:
        target = (path.parent / raw.decode("utf-8")).resolve()
        try:
            relative = target.relative_to(src.resolve())
        except ValueError:
            raise SystemExit(f"{path}: includes {raw.decode()}, outside {RUNTIME_SRC}") from None
        if not target.is_file():
            raise SystemExit(f"{path}: includes {raw.decode()}, which does not exist")
        out.append(PurePosixPath(relative.as_posix()))
    return out


def vendored_files_on_disk(root: Path) -> set[str]:
    """Every file under `mod/src/runtime/`: sources and the data files they embed."""
    target = root / VENDOR
    if not target.is_dir():
        return set()
    return {path.relative_to(target).as_posix() for path in target.rglob("*") if path.is_file()}


def expected(root: Path) -> dict[str, tuple[bytes, bytes]]:
    """Every file the vendoring produces: {destination path: (source bytes, vendored bytes)}.

    A data file a source embeds is vendored unchanged (source bytes == vendored bytes).
    """
    src = root / RUNTIME_SRC
    files = {}
    data: set[PurePosixPath] = set()
    for path in sorted(src.rglob("*.rs")):
        relative = PurePosixPath(path.relative_to(src).as_posix())
        if relative in SKIP:
            continue
        original = path.read_bytes()
        data.update(included_files(src, path, original))
        # The runtime stops being a crate root: its own paths move under the mod's `runtime`
        # module. Token-level enough: `crate::` is a path qualifier in this tree and never
        # appears inside a string or a character literal (checked by the test that reads it).
        text = original.decode("utf-8").replace("crate::", PREFIX)
        destination = vendored_name(relative)
        if destination == PurePosixPath("mod.rs"):
            text = ROOT_HEADER + text
        files[str(destination)] = (original, text.encode("utf-8"))
    for relative in sorted(data):
        if relative.suffix == ".rs":
            raise SystemExit(f"{RUNTIME_SRC / relative}: an included .rs file would be rewritten")
        content = (src / relative).read_bytes()
        files[str(relative)] = (content, content)
    return files


def load_lock(root: Path) -> dict:
    try:
        return json.loads((root / LOCK).read_text())
    except (OSError, json.JSONDecodeError):
        return {}


def recorded_files(root: Path) -> dict[str, dict]:
    """The lock's per-file rows, or an empty map with the schema problem already reported."""
    lock = load_lock(root)
    if lock.get("schema") != LOCK_SCHEMA:
        return {}
    return lock.get("files", {})


def lock_drift(root: Path) -> list[str]:
    """Every hand edit to the committed copy: `mod/src/runtime/**` against `mod/vendor.lock`.

    This is the check that always applies. It says nothing about the runtime crate: the mod
    carries the commit its lock records, and that commit is refreshed in a mod PR, so a runtime
    change alone must not turn this red.
    """
    problems = []
    lock = load_lock(root)
    if lock.get("schema") != LOCK_SCHEMA:
        problems.append(f"{LOCK}: missing or not schema {LOCK_SCHEMA}")
    recorded = lock.get("files", {})
    on_disk = vendored_files_on_disk(root)
    for name, entry in sorted(recorded.items()):
        path = root / VENDOR / name
        want = entry.get("sha256")
        if not path.is_file():
            problems.append(f"{path}: recorded in {LOCK} but missing")
        elif sha256(path.read_bytes()) != want:
            problems.append(
                f"{path}: edited by hand; it is generated from {RUNTIME_SRC} (run tools/vendor.py)"
            )
    for name in sorted(on_disk - set(recorded)):
        problems.append(f"{VENDOR / name}: vendored file is not recorded in {LOCK}")
    return problems


def source_drift(root: Path) -> list[str]:
    """Every difference between the committed copy and the runtime source as it is now.

    This is the check a PR that touches `mod/**` or this tool must pass: it means the mod carries
    the runtime's current behaviour, not an older commit of it.
    """
    problems = []
    files = expected(root)
    recorded = recorded_files(root)
    if load_lock(root).get("schema") != LOCK_SCHEMA:
        problems.append(f"{LOCK}: missing or not schema {LOCK_SCHEMA}")
    for name, (source_bytes, vendored_bytes) in sorted(files.items()):
        entry = recorded.get(name)
        want = sha256(vendored_bytes)
        if entry is None:
            problems.append(f"{VENDOR / name}: vendored copy is not in {LOCK}")
        elif entry.get("sha256") != want:
            problems.append(
                f"{VENDOR / name}: out of date with {RUNTIME_SRC} "
                f"(lock {entry.get('sha256')}, source {want})"
            )
        if entry is not None and entry.get("source_sha256") != sha256(source_bytes):
            problems.append(f"{RUNTIME_SRC / name.replace('mod.rs', 'lib.rs')}: changed since {LOCK}")
    on_disk = vendored_files_on_disk(root)
    for name in sorted(on_disk - set(files)):
        problems.append(f"{VENDOR / name}: vendored file has no source in {RUNTIME_SRC}")
    return problems


def drift(root: Path) -> list[str]:
    """Both checks: the committed copy is unedited and matches the runtime source as it is now."""
    return lock_drift(root) + source_drift(root)


def write(root: Path) -> None:
    files = expected(root)
    target = root / VENDOR
    target.mkdir(parents=True, exist_ok=True)
    for name, (_, vendored_bytes) in sorted(files.items()):
        destination = target / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(vendored_bytes)
    # A file whose source is gone (or that no source embeds any more) stops being part of the mod.
    for name in vendored_files_on_disk(root) - set(files):
        (target / name).unlink()
    lock = {
        "schema": LOCK_SCHEMA,
        "source": str(RUNTIME_SRC),
        "source_commit": source_commit(root),
        "note": (
            "Generated by tools/vendor.py; do not edit. One commit of horizon-java, copied into "
            "the native mod's one crate."
        ),
        "files": {
            name: {
                "sha256": sha256(vendored_bytes),
                "source_sha256": sha256(source_bytes),
                "source": f"{RUNTIME_SRC / (name if name != 'mod.rs' else 'lib.rs')}",
            }
            for name, (source_bytes, vendored_bytes) in sorted(files.items())
        },
    }
    (root / LOCK).write_text(json.dumps(lock, indent=2, sort_keys=True) + "\n")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail unless the committed copy is unedited and matches the runtime source (a mod PR)",
    )
    parser.add_argument(
        "--check-lock",
        action="store_true",
        help="fail unless the committed copy matches mod/vendor.lock (always applies)",
    )
    parser.add_argument("--repo", type=Path, default=None, help="the tree to vendor (default: this one)")
    args = parser.parse_args(argv)
    root = (args.repo or repo_root()).resolve()
    if args.check or args.check_lock:
        problems = lock_drift(root) if args.check_lock else drift(root)
        for problem in problems:
            print(f"drift: {problem}", file=sys.stderr)
        if problems:
            print(
                f"{len(problems)} vendored file(s) are not what tools/vendor.py produces",
                file=sys.stderr,
            )
            return 1
        if args.check_lock:
            print(f"{len(load_lock(root).get('files', {}))} vendored file(s) match {LOCK}")
            return 0
        recorded = load_lock(root).get("source_commit")
        current = source_commit(root)
        if recorded and recorded != current:
            print(
                f"note: {LOCK} records {recorded}, this tree is {current}; "
                "the vendored files still match (run tools/vendor.py to refresh the record)",
                file=sys.stderr,
            )
        print(f"{len(expected(root))} vendored file(s) match {RUNTIME_SRC}")
        return 0
    write(root)
    print(f"vendored {len(expected(root))} file(s) into {VENDOR}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
